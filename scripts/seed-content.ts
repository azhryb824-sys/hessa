async function main() {
  for (const course of await prisma.course.findMany({
    where: { teacher: { email: "teacher@hessa.local" } },
  })) {
    const rows = contents[course.subject];
    if (!rows) continue;
    for (let i = 0; i < rows.length; i++)
      await prisma.lesson.updateMany({
        where: { courseId: course.id, order: i + 1 },
        data: {
          title: rows[i].title,
          content: rows[i].content,
          type: "READING",
        },
      });
  }
  const parent = await prisma.user.findUnique({
    where: { email: "parent@hessa.local" },
  });
  const student = await prisma.user.findUnique({
    where: { email: "student@hessa.local" },
  });
  if (parent && student)
    await prisma.parentLink.upsert({
      where: {
        parentId_studentId: { parentId: parent.id, studentId: student.id },
      },
      create: { parentId: parent.id, studentId: student.id },
      update: {},
    });
  console.log("Educational lesson content ready");
}
main().finally(() => prisma.$disconnect());
